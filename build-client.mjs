/**
 * Build client.js from client/*.js: the modules share one factory scope, in
 * file-name order, inside DSH's module-loader wrapper. No dependencies.
 * Run: `node build-client.mjs` (add `--check` to fail if client.js is stale).
 */
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const dir = path.join(here, 'client');
const parts = readdirSync(dir).filter((f) => f.endsWith('.js')).sort();
const body = parts.map((file) => `// ===== client/${file}\n${readFileSync(path.join(dir, file), 'utf8').trimEnd()}\n`).join('\n');
const indented = body.split('\n').map((line) => (line ? '    ' + line : line)).join('\n');
const output = `/* AITP Atlas — client half. Generated by build-client.mjs from client/*.js; edit those files. */
window.__ModuleLoader__.load({
  id: 'aitp-atlas',
  factory(require) {
    'use strict';
${indented}
  },
});
`;
const target = path.join(here, 'client.js');
if (process.argv.includes('--check')) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (current !== output) {
    console.error('client.js is stale: run node build-client.mjs');
    process.exit(1);
  }
  console.log('client.js is current');
} else {
  writeFileSync(target, output, 'utf8');
  console.log(`client.js written from ${parts.length} modules (${output.split('\n').length} lines)`);
}
